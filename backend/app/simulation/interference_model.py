import math
from typing import Dict, List, Tuple
from ..models.cell import Cell
from ..models.user import User
from .signal_model import SignalModel


class InterferenceModel:
    """
    Computes inter-cell interference and user SINR using linear power additions.
    """

    @classmethod
    def calculate_user_sinr(
        cls,
        user: User,
        cells: Dict[str, Cell],
    ) -> Tuple[float, float, float]:
        """
        Calculates (RSRP_dBm, SINR_dB, total_interference_mw) for a user given active cells.
        Returns:
            serving_rsrp_dbm: float
            sinr_db: float
            interference_mw: float
        """
        if not user.serving_cell or user.serving_cell not in cells:
            return -140.0, -30.0, 0.0

        serving_cell = cells[user.serving_cell]
        if not serving_cell.is_active:
            return -140.0, -30.0, 0.0

        dist_serving = SignalModel.calculate_distance(user.x, user.y, serving_cell.x, serving_cell.y)
        serving_rsrp = SignalModel.calculate_rsrp(serving_cell.tx_power_dbm, dist_serving)
        serving_power_mw = SignalModel.dbm_to_mw(serving_rsrp)

        # Sum linear interference from all other active cells
        interference_mw = 0.0
        for cell_id, cell in cells.items():
            if cell_id == user.serving_cell or not cell.is_active:
                continue
            dist_int = SignalModel.calculate_distance(user.x, user.y, cell.x, cell.y)
            rsrp_int = SignalModel.calculate_rsrp(cell.tx_power_dbm, dist_int)
            interference_mw += SignalModel.dbm_to_mw(rsrp_int)

        noise_mw = SignalModel.dbm_to_mw(SignalModel.NOISE_FLOOR_DBM)
        denominator = interference_mw + noise_mw

        if denominator <= 0.0 or serving_power_mw <= 0.0:
            sinr_db = -30.0
        else:
            sinr_linear = serving_power_mw / denominator
            sinr_db = 10.0 * math.log10(max(sinr_linear, 1e-6))

        return serving_rsrp, sinr_db, interference_mw

    @classmethod
    def calculate_cell_interference_matrix(
        cls,
        cells: Dict[str, Cell]
    ) -> Dict[str, float]:
        """
        Calculates the normalized interference generated by each cell to its neighbors.
        Interference is scaled to normalized index (10^((RSRP + 100)/10)).
        """
        cell_interference: Dict[str, float] = {cid: 0.0 for cid in cells}
        for cid, cell in cells.items():
            if not cell.is_active:
                continue
            # Interference radiated towards neighbor locations
            total_radiated = 0.0
            for nid in cell.neighbors:
                if nid in cells and cells[nid].is_active:
                    ncell = cells[nid]
                    dist = SignalModel.calculate_distance(cell.x, cell.y, ncell.x, ncell.y)
                    rsrp_at_neighbor = SignalModel.calculate_rsrp(cell.tx_power_dbm, dist)
                    # Scaled interference index: > 0 for typical cellular signals
                    scaled_int = math.pow(10.0, (rsrp_at_neighbor + 100.0) / 10.0)
                    total_radiated += scaled_int
            cell_interference[cid] = round(total_radiated, 2)
        return cell_interference
