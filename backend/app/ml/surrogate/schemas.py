"""Pydantic schemas and data transfer objects for ML Decision Intelligence Surrogate.

AI PREDICTS -> DIGITAL TWIN VERIFIES -> REFEREE DECIDES
"""

from __future__ import annotations

import time
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ActionTypeCategory(str, Enum):
    STATUS_QUO = "STATUS_QUO"
    POWER_UP = "POWER_UP"
    POWER_DOWN = "POWER_DOWN"
    SHUTDOWN = "SHUTDOWN"
    COMPROMISE = "COMPROMISE"


class PreActionFeatures(BaseModel):
    """
    Feature vector captured strictly BEFORE candidate action execution.
    Zero future leakage; purely based on current network state and proposed action parameters.
    """
    base_coverage_pct: float = Field(..., description="Current network-wide coverage percentage")
    base_interference: float = Field(..., description="Current network-wide interference index")
    base_total_energy: float = Field(..., description="Current network-wide total energy consumption (Watts)")
    base_avg_sinr: float = Field(..., description="Current network average SINR in dB")
    base_min_sinr: float = Field(..., description="Current network minimum SINR in dB")
    base_active_cells: int = Field(..., description="Number of currently active cells")
    base_cell_utilization: float = Field(..., description="Mean cell load utilization")
    target_cell_idx: int = Field(..., description="Target cell index (1-6 for CELL_01..06, 0 for ALL/STATUS_QUO)")
    target_cell_curr_pwr: float = Field(..., description="Target cell current tx power (dBm)")
    target_cell_proposed_pwr: float = Field(..., description="Proposed tx power for target cell (dBm)")
    target_cell_power_delta: float = Field(..., description="Proposed power delta (dBm)")
    target_cell_is_shutdown: int = Field(..., description="1 if shutdown proposed, else 0")
    target_cell_curr_load: float = Field(..., description="Current load fraction of target cell [0, 1]")
    target_cell_curr_interference: float = Field(..., description="Current interference caused by target cell")
    target_cell_connected_users: int = Field(..., description="Number of connected users on target cell")
    target_cell_neighbor_count: int = Field(..., description="Number of neighbors configured for target cell")
    target_cell_neighbor_mean_pwr: float = Field(..., description="Average tx power of neighbor cells (dBm)")
    action_num_cells_modified: int = Field(..., description="Number of cells modified in this joint action")
    action_total_delta_db: float = Field(..., description="Sum of absolute power deltas across all modified cells")
    traffic_demand_multiplier: float = Field(..., description="Aggregate user traffic demand scale factor")


class SurrogatePrediction(BaseModel):
    """
    Predictions generated by the ML surrogate BEFORE digital twin simulation.
    """
    model_config = {"protected_namespaces": ()}
    candidate_id: str
    target_cell: str
    predicted_coverage_delta: float = Field(..., description="Predicted change in coverage percentage (%)")
    predicted_coverage_pct: float = Field(..., description="Base coverage + predicted delta (%)")
    predicted_interference_delta: float = Field(..., description="Predicted change in total interference index")
    predicted_interference: float = Field(..., description="Base interference + predicted delta")
    predicted_energy_delta: float = Field(..., description="Exact deterministic change in energy (Watts)")
    predicted_total_energy: float = Field(..., description="Base energy + deterministic delta (Watts)")
    predicted_is_safe: bool = Field(..., description="Whether predicted coverage satisfies >= 95.0% safe threshold")
    safety_risk_score: float = Field(..., description="Estimated risk score [0, 1] (higher = unsafe)")
    surrogate_objective_score: float = Field(0.0, description="Surrogate multi-objective score")
    prediction_latency_ms: float = Field(..., description="Surrogate inference latency in milliseconds")
    prediction_timestamp: float = Field(default_factory=time.time)
    model_version: str = "xgb-action-surrogate-v1.0"
    data_provenance: str = "Simulated radio environment (3GPP Macro Urban TR 36.814) — not physical testbed"
    out_of_distribution: bool = Field(default=False, description="Whether proposed action is outside validated operational envelope")
    ood_warning: Optional[str] = Field(default=None, description="Detailed out-of-distribution explanation if applicable")


class CandidateTwinVerification(BaseModel):
    """
    Authoritative verification produced by the Digital Twin Shadow Simulator.
    """
    candidate_id: str
    actual_coverage_delta: float
    actual_coverage_pct: float
    actual_interference_delta: float
    actual_interference: float
    actual_energy_delta: float
    actual_total_energy: float
    actual_is_safe: bool
    violated_constraints: List[str]
    actual_objective_score: float
    verification_latency_ms: float
    verification_timestamp: float = Field(default_factory=time.time)


class PredictionVerificationPair(BaseModel):
    """
    Side-by-side auditable comparison of ML prediction vs Digital Twin verification.
    """
    candidate_id: str
    description: str
    target_cell: str
    action_type: str
    prediction: SurrogatePrediction
    verification: CandidateTwinVerification
    coverage_error_abs: float = Field(..., description="|actual - predicted| coverage delta error")
    interference_error_abs: float = Field(..., description="|actual - predicted| interference delta error")
    safety_classification_match: bool = Field(..., description="predicted_is_safe == actual_is_safe")
    is_false_negative_risk: bool = Field(..., description="Predicted SAFE when actually UNSAFE (critical safety error)")
    arbitration_phase: str = "VERIFIED_BY_TWIN"


class DecisionIntelligenceAudit(BaseModel):
    """
    Comprehensive auditable log for the arbitration cycle.
    """
    cycle: int
    decision_id: str
    timestamp: float = Field(default_factory=time.time)
    total_candidates_screened: int
    ml_inference_total_ms: float
    twin_verification_total_ms: float
    candidate_comparisons: List[PredictionVerificationPair]
    top_predicted_candidate_id: str
    top_verified_candidate_id: str
    ranking_concordance: bool = Field(..., description="Did ML top-1 match Digital Twin top-1?")
    mean_coverage_error: float
    mean_interference_error: float
    unsafe_candidates_flagged: int
    false_negatives_count: int
    status: str = "AUDITED"
